"""Builds the 3D building from a FacilityMap.

This module displays; it contains no game rules.
"""

import math
from dataclasses import dataclass

from panda3d.core import TransparencyAttrib
from ursina import Entity, Vec3, color, destroy

from core.level import Cell, FacilityMap
from core.props import Prop
from core.signs import Sign
from core.texts import current_language
from view.abandon import ceiling_holes, scatter_debris, wall_textures
from view.coords import cell_to_world
from view.furniture import DESK, SHELF, FurnitureStyle, place_furniture
from view.lighting import make_lit
from view.model_loader import (
    EXIT_DOOR,
    GENERATOR,
    ModelLoadError,
    ModelSpec,
    place_model,
)
from view.props import CATALOG

WALL_HEIGHT = 3.0
# Textures generated by tools/make_textures.py, stored in assets/textures/.
FLOOR_TEXTURE = "floor_tiles"
CEILING_TEXTURE = "ceiling_tiles"


@dataclass(frozen=True)
class ItemStyle:
    """How an object looks: colour, size, texture, 3D model, furniture."""

    color: object
    scale: tuple[float, float, float]
    height: float
    solid: bool = False  # a solid object blocks the player
    support: FurnitureStyle | None = None  # the furniture the object rests on
    texture: str | None = (
        None  # image from assets/textures/; otherwise, the colour alone
    )
    model: ModelSpec | None = None  # 3D model; otherwise, a textured block
    against_wall: bool = False  # backed against the nearest wall, facing the room


FUSE_STYLE = ItemStyle(
    color.yellow, (0.3, 0.12, 0.12), 1.0, support=SHELF, texture="fuse"
)
POWER_PANEL_STYLE = ItemStyle(
    color.azure, (0.9, 0.85, 0.9), 0.43, solid=True, model=GENERATOR
)
NOTE_STYLE = ItemStyle(
    color.white, (0.3, 0.02, 0.34), 0.9, support=DESK, texture="note"
)
BATTERY_STYLE = ItemStyle(
    color.orange, (0.15, 0.3, 0.15), 0.9, support=SHELF, texture="battery"
)
EXIT_STYLE = ItemStyle(
    color.green, (1.3, 2.3, 0.4), 1.15, model=EXIT_DOOR, against_wall=True
)
DOCUMENT_STYLE = ItemStyle(
    color.light_gray, (0.26, 0.02, 0.32), 0.9, support=DESK, texture="document"
)
LOCKER_STYLE = ItemStyle(
    color.dark_gray, (0.9, 2.2, 0.9), 1.1, solid=True, texture="locker"
)
KEYCARD_STYLE = ItemStyle(
    color.cyan, (0.3, 0.02, 0.22), 0.9, support=DESK, texture="keycard"
)
SECURITY_DOOR_STYLE = ItemStyle(
    color.brown, (1, 2.4, 1), 1.2, solid=True, texture="security_door"
)
DOOR_SIZE = (1.0, 2.4, 0.08)  # width, height, thickness of the door leaf
DOOR_TEXTURE = "door"
DEBRIS_HEIGHT = 0.01  # just above the floor
SIGN_SIZE = (0.9, 0.225)  # width, height of a sign, in metres
SIGN_HEIGHT = 2.25  # above the doors
GLOWING_SIGNS = {"sign.exit_right"}  # emergency exit signs stay visible in the dark
DEBRIS_LAYER = 0.0005
FALLEN_TILE_HEIGHT = 0.04  # above the other debris
CABLE_COLOR = color.rgb32(26, 26, 26)
CABLE_THICKNESS = 0.025
PROP_COLLIDER = (0.9, 1.5, 0.9)  # the volume that stops the player, per cell
DOOR_OPEN_ANGLE = 95  # degrees: the open door swings almost flat against the wall


class LevelRenderer:
    """Builds the walls, floor, ceiling and objects of a level."""

    def __init__(
        self,
        level: FacilityMap,
        wall_height: float = WALL_HEIGHT,
        app=None,
        signs: list[Sign] | tuple[Sign, ...] = (),
        props: list[Prop] | tuple[Prop, ...] = (),
    ) -> None:
        self._level = level
        self._props = tuple(props)
        self._signs = tuple(signs)
        self._sign_entities: list[tuple[Sign, Entity]] = []
        self._app = app  # without an application, no 3D models: coloured blocks instead
        self._wall_height = wall_height
        self._items: dict[Cell, Entity] = {}
        self._doors: dict[Cell, tuple[Entity, Entity]] = {}  # (gond, battant)
        self._water_points: list[Vec3] = []

    def build(self) -> None:
        self._build_floor_and_ceiling()
        self._build_walls()
        self._build_debris()
        self._build_ceiling_damage()
        self._build_signs()
        self._build_props()
        self._build_items()
        self._build_doors()

    def sync_doors(self, doors) -> list[Cell]:
        """Opens or closes the displayed doors to match the core.

        Returns the cells of the doors that moved, to play a sound.
        """
        moved = []
        for door in doors:
            hinge, panel = self._doors[door.cell]
            is_open = not door.is_closed
            if (hinge.rotation_y != 0) == is_open:
                continue
            hinge.rotation_y = DOOR_OPEN_ANGLE if is_open else 0
            panel.collider = None if is_open else "box"
            moved.append(door.cell)
        return moved

    @property
    def water_points(self) -> list[Vec3]:
        """The top of damp walls facing a room: where the drops fall from."""
        return self._water_points

    def show_signs_in(self, language: str) -> None:
        """Changes the text on the signs, for example when the language changes."""
        for sign, entity in self._sign_entities:
            entity.texture = _sign_texture(sign, language)

    def remove_item(self, cell: Cell) -> None:
        """Removes the object shown on a cell, for example when it is picked up."""
        entity = self._items.pop(cell, None)
        if entity is not None:
            destroy(entity)

    def _build_floor_and_ceiling(self) -> None:
        width, height = self._level.width, self._level.height
        center_cell = ((height - 1) / 2, (width - 1) / 2)
        make_lit(
            Entity(
                model="plane",
                scale=(width, 1, height),
                position=cell_to_world(center_cell),
                texture=FLOOR_TEXTURE,
                texture_scale=(width, height),  # the texture repeats once per cell
                color=color.white,
                collider="box",
            )
        )
        make_lit(
            Entity(
                model="plane",
                scale=(width, 1, height),
                position=cell_to_world(center_cell, self._wall_height),
                rotation_x=180,
                texture=CEILING_TEXTURE,
                texture_scale=(width, height),
                color=color.white,
            )
        )

    def _build_walls(self) -> None:
        textures = wall_textures(self._level)  # cracks, damp, holes, claw marks
        self._water_points = [
            cell_to_world(cell, self._wall_height - 0.4)
            for cell, texture in textures.items()
            if texture == "wall_water" and self._faces_a_room(cell)
        ]
        for cell in self._level.wall_cells():
            make_lit(
                Entity(
                    model="cube",
                    position=cell_to_world(cell, self._wall_height / 2),
                    scale=(1, self._wall_height, 1),
                    texture=textures[cell],
                    color=color.white,
                    collider="box",
                )
            )

    def _build_items(self) -> None:
        level = self._level
        placements = [
            (level.fuse_cell, FUSE_STYLE),
            (level.power_panel_cell, POWER_PANEL_STYLE),
            (level.note_cell, NOTE_STYLE),
            (level.exit_cell, EXIT_STYLE),
        ]
        placements += [(cell, BATTERY_STYLE) for cell in level.battery_cells]
        placements += [(cell, DOCUMENT_STYLE) for cell in level.document_cells]
        placements += [(cell, LOCKER_STYLE) for cell in level.hiding_spot_cells]
        placements += [
            (cell, SECURITY_DOOR_STYLE) for cell in level.security_door_cells
        ]
        if level.keycard_cell is not None:
            placements.append((level.keycard_cell, KEYCARD_STYLE))
        for cell, style in placements:
            if style.model is not None and self._app is not None:
                self._items[cell] = self._spawn_model(cell, style)
            else:
                self._items[cell] = self._spawn_item(
                    style, self._item_position(cell, style)
                )

    def _spawn_model(self, cell: Cell, style: ItemStyle) -> Entity:
        """A 3D model, facing the room; a coloured block if it is missing."""
        holder = Entity(position=cell_to_world(cell))
        wall_side = self._level.wall_side(cell) if style.against_wall else None
        if wall_side is not None:
            d_row, d_col = wall_side
            depth = style.scale[2]
            holder.position += Vec3(d_col, 0, -d_row) * (0.5 - depth / 2)
            holder.rotation_y = math.degrees(
                math.atan2(-d_col, d_row)
            )  # back against the wall
        try:
            place_model(self._app, style.model, holder)
        except ModelLoadError as error:
            print(f"{error} A coloured block replaces it.")
            destroy(holder)
            return self._spawn_item(style, self._item_position(cell, style))
        if style.solid:
            Entity(
                parent=holder,
                model="cube",
                y=style.scale[1] / 2,
                scale=style.scale,
                collider="box",
                visible=False,
            )
        return holder

    def _build_ceiling_damage(self) -> None:
        """Fallen tiles: a black hole in the ceiling, the broken tile on the floor, cables."""
        for hole in ceiling_holes(self._level):
            self._flat_decal(
                "ceiling_hole", cell_to_world(hole.cell, self._wall_height - 0.01), -90
            )
            self._flat_decal(
                "debris_ceiling", cell_to_world(hole.cell, FALLEN_TILE_HEIGHT), 90
            )
            for cable in hole.cables:
                dx, dz = cable.offset
                make_lit(
                    Entity(
                        model="cube",
                        position=cell_to_world(
                            hole.cell, self._wall_height - cable.length / 2
                        )
                        + Vec3(dx, 0, dz),
                        rotation_z=cable.tilt,
                        scale=(CABLE_THICKNESS, cable.length, CABLE_THICKNESS),
                        color=CABLE_COLOR,
                    )
                )

    @staticmethod
    def _flat_decal(texture: str, position: Vec3, rotation_x: float) -> None:
        """A flat image, facing up (90) or down (-90)."""
        decal = make_lit(
            Entity(
                model="quad",
                texture=texture,
                position=position,
                rotation_x=rotation_x,
                double_sided=True,
            )
        )
        decal.setTransparency(TransparencyAttrib.MAlpha)

    def _build_props(self) -> None:
        """Each piece of furniture is built from blocks, then merged into one 3D object."""
        for prop in self._props:
            d_row, d_col = prop.facing
            holder = Entity(
                position=cell_to_world(prop.anchor),
                rotation_y=math.degrees(
                    math.atan2(d_col, -d_row)
                ),  # facing its direction
            )
            for part in CATALOG[prop.kind]:
                Entity(
                    parent=holder,
                    model="cube",
                    position=part.center,
                    scale=part.size,
                    color=color.rgb32(*part.color),
                )
            holder.combine()  # one mesh per piece of furniture: much lighter to draw
            make_lit(holder)
            for cell in prop.cells:  # the player bumps into the occupied cells
                Entity(
                    model="cube",
                    position=cell_to_world(cell, PROP_COLLIDER[1] / 2),
                    scale=PROP_COLLIDER,
                    collider="box",
                    visible=False,
                )

    def _build_signs(self) -> None:
        """Each sign is stuck on the wall face, facing the corridor."""
        language = current_language()
        for sign in self._signs:
            d_row, d_col = sign.facing
            outward = Vec3(d_col, 0, -d_row)  # from the wall towards the corridor
            plate = Entity(
                model="quad",
                texture=_sign_texture(sign, language),
                position=cell_to_world(sign.wall, SIGN_HEIGHT) + outward * 0.51,
                rotation_y=math.degrees(math.atan2(-outward.x, -outward.z)),
                scale=SIGN_SIZE,
            )
            if sign.key not in GLOWING_SIGNS:
                make_lit(plate)  # the other signs stay in the shadows
            self._sign_entities.append((sign, plate))

    def _faces_a_room(self, cell: Cell) -> bool:
        row, col = cell
        neighbours = ((row - 1, col), (row + 1, col), (row, col - 1), (row, col + 1))
        return any(not self._level.is_wall(n) for n in neighbours)

    def _build_debris(self) -> None:
        """Papers, rubble, tile shards and stains, lying flat on the floor."""
        for index, debris in enumerate(scatter_debris(self._level)):
            dx, dz = debris.offset
            height = DEBRIS_HEIGHT + index * DEBRIS_LAYER  # keeps them from overlapping
            decal = make_lit(
                Entity(
                    model="quad",
                    texture=debris.texture,
                    position=cell_to_world(debris.cell, height) + Vec3(dx, 0, dz),
                    rotation=(90, debris.angle, 0),
                    scale=debris.size,
                    double_sided=True,
                )
            )
            decal.setTransparency(TransparencyAttrib.MAlpha)

    def _build_doors(self) -> None:
        """Each door leaf turns around a hinge placed against the wall."""
        for cell in self._level.door_cells:
            row, col = cell
            across_columns = self._level.is_wall(
                (row, col - 1)
            )  # walls to the left and right
            frame = Entity(
                position=cell_to_world(cell), rotation_y=0 if across_columns else 90
            )
            hinge = Entity(parent=frame, x=-DOOR_SIZE[0] / 2)
            width, height, _ = DOOR_SIZE
            panel = make_lit(
                Entity(
                    parent=hinge,
                    model="cube",
                    position=(width / 2, height / 2, 0),
                    scale=DOOR_SIZE,
                    texture=DOOR_TEXTURE,
                    collider="box",
                )
            )
            self._doors[cell] = (hinge, panel)

    def _item_position(self, cell: Cell, style: ItemStyle) -> Vec3:
        """On its furniture if it has any (against the wall), otherwise at the cell centre."""
        wall_side = self._level.wall_side(cell)
        if style.support is None or wall_side is None:
            return cell_to_world(cell, style.height)
        top = place_furniture(cell, wall_side, style.support)
        return top + Vec3(0, style.scale[1] / 2, 0)  # resting on it, not sunk into it

    @staticmethod
    def _spawn_item(style: ItemStyle, position: Vec3) -> Entity:
        return make_lit(
            Entity(
                model="cube",
                position=position,
                scale=style.scale,
                texture=style.texture,
                color=color.white if style.texture else style.color,
                collider="box" if style.solid else None,
            )
        )


def _sign_texture(sign: Sign, language: str) -> str:
    """'sign.archives' in English -> the texture sign_archives_en."""
    return f"sign_{sign.key.removeprefix('sign.')}_{language}"
